def get_final_output(initial_stones):
    n = len(initial_stones)

    # Each position represents a bit with weight 2^i.
    # The circular transfer preserves this value modulo 2^n.
    total = sum(stone << i for i, stone in enumerate(initial_stones))

    # Keep only the lowest n bits.
    total &= (1 << n) - 1

    # Convert bits back to the original stone order.
    return "".join(str((total >> i) & 1) for i in range(n))


